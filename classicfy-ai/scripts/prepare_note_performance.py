"""Extract raw 11D R, fit an explicit train scaler, or export scaled pre-AE arrays.

extract --manifest records.json --out new-directory
fit-scaler --manifest new-directory/manifest.json --out scaler.json
transform --record new-directory/records/<ref> --scaler scaler.json --out ready.npz

Input records carry dataset, record_key, work_key, split, xml_path, and optional
score_cache, traversal, selected_channels, pedal_observations, alignment_policy.
ASAP additionally needs asap_root/nasap_root; ATEPP needs score_midi_path,
performance_midi_path, alignment_cache, and a fingerprinted xml_bridge JSON.
Existing split assignments are required and never generated by this command.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'src'))

from embedding.note_performance_data import export_scaled_note_performance, load_note_performance, save_note_performance
from embedding.note_score_context_data import load_note_score_context, save_note_score_context
from features.note_performance import note_performance_schema, summarize_note_performance
from features.note_performance_normalization import (
    fit_note_performance_scaler, load_note_performance_scaler, save_note_performance_scaler, validate_work_splits,
)
from preprocessing.asap_loader import ASAPLoader
from preprocessing.note_performance_adapters import AlignmentPolicy, prepare_asap_note_performance, prepare_atepp_note_performance
from preprocessing.performance_midi import PedalObservation


def _path(base, value):
    path = Path(value).expanduser()
    return path if path.is_absolute() else base / path


def _json_value(base, value):
    return json.loads(_path(base, value).read_text(encoding='utf-8')) if isinstance(value, str) else value


def _prepare(entry, base):
    score = load_note_score_context(_path(base, entry['score_cache']))[0] if entry.get('score_cache') else None
    observations = {}
    for item in entry.get('pedal_observations', []):
        key = (item['port'], item['channel'], item['number'])
        if key in observations:
            raise ValueError('Duplicate pedal observation scope')
        observations[key] = PedalObservation(**{k: v for k, v in item.items() if k not in {'port', 'channel', 'number'}})
    common = {'work_key': entry['work_key'], 'split': entry['split'], 'score_features': score,
              'traversal': tuple(entry['traversal']) if 'traversal' in entry else None,
              'selected_channels': entry.get('selected_channels'), 'pedal_observations': observations,
              'policy': AlignmentPolicy(**entry.get('alignment_policy', {})),
              'grace_reference_keys': entry.get('grace_reference_keys', ())}
    xml = _path(base, entry['xml_path'])
    if entry['dataset'] == 'ASAP':
        loader = ASAPLoader(_path(base, entry['asap_root']), note_alignment_root=_path(base, entry['nasap_root']))
        sample = loader.get_sample(entry['record_key'])
        return prepare_asap_note_performance(sample, xml, aliases=_json_value(base, entry.get('aliases')), **common)
    if entry['dataset'] == 'ATEPP':
        return prepare_atepp_note_performance(xml, _path(base, entry['score_midi_path']),
                                               _path(base, entry['performance_midi_path']),
                                               _path(base, entry['alignment_cache']), _json_value(base, entry['xml_bridge']),
                                               record_key=entry['record_key'], **common)
    raise ValueError('Supported dataset adapters are ASAP and ATEPP')


def extract_manifest(path, out):
    path, out = Path(path), Path(out)
    payload = json.loads(path.read_text(encoding='utf-8'))
    entries = payload['records'] if isinstance(payload, dict) else payload
    if not isinstance(entries, list) or not entries:
        raise ValueError('Input manifest must contain nonempty records')
    validate_work_splits(entries)
    identities = [(entry['dataset'], entry['record_key']) for entry in entries]
    if len(set(identities)) != len(identities):
        raise ValueError('Input manifest contains duplicate recording IDs')
    out.mkdir(parents=True, exist_ok=False)
    results, score_splits = [], {}
    for entry in entries:
        row = {name: entry[name] for name in ('dataset', 'record_key', 'work_key', 'split')}
        try:
            s, r = _prepare(entry, path.parent)
            assigned = score_splits.get(s.source_sha256)
            if r.split != 'unassigned':
                if assigned is not None and assigned != r.split:
                    raise ValueError('Identical XML score crosses dataset splits')
                score_splits[s.source_sha256] = r.split
            score_ref = Path('scores') / s.cache_key
            if not (out / score_ref).exists():
                save_note_score_context(s, out / score_ref)
            record_ref = Path('records') / hashlib.sha256((r.dataset + '\0' + r.record_key).encode()).hexdigest()
            save_note_performance(r, out / record_ref)
            row.update(status='extracted', score_cache=str(score_ref), performance_cache=str(record_ref),
                       fingerprint=r.fingerprint, score_ref=s.cache_key, score_source_sha256=s.source_sha256,
                       summary=summarize_note_performance(r))
        except Exception as exc:
            row.update(status='rejected', error_type=type(exc).__name__, reason=str(exc))
        results.append(row)
        print(f'{row["status"]}: {entry["dataset"]}/{entry["record_key"]}', flush=True)
    manifest = {'schema': note_performance_schema(), 'source_manifest_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                'records': results, 'split_policy': 'caller supplied, work-disjoint; unchanged',
                'stage': 'R extraction only; no scaler or AE fit'}
    (out / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2, allow_nan=False), encoding='utf-8')
    return manifest


def fit_manifest_scaler(path, out):
    path = Path(path)
    payload = json.loads(path.read_text(encoding='utf-8'))
    if payload.get('schema') != note_performance_schema():
        raise ValueError('Extraction manifest R schema mismatch')
    validate_work_splits(payload['records'])
    training = []
    for entry in payload['records']:
        if entry['status'] == 'extracted' and entry['split'] == 'train':
            record = load_note_performance(_path(path.parent, entry['performance_cache']))
            if (record.fingerprint != entry['fingerprint'] or record.work_key != entry['work_key']
                    or record.split != entry['split'] or record.record_key != entry['record_key']
                    or record.dataset != entry['dataset']):
                raise ValueError('Extraction manifest and R cache identities disagree')
            training.append(record)
    scaler = fit_note_performance_scaler(training, fit_manifest_id=hashlib.sha256(path.read_bytes()).hexdigest())
    save_note_performance_scaler(scaler, out)
    return scaler


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest='command', required=True)
    for name in ('extract', 'fit-scaler'):
        command = commands.add_parser(name)
        command.add_argument('--manifest', type=Path, required=True)
        command.add_argument('--out', type=Path, required=True)
    command = commands.add_parser('transform')
    command.add_argument('--record', type=Path, required=True)
    command.add_argument('--scaler', type=Path, required=True)
    command.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    if args.command == 'extract':
        manifest = extract_manifest(args.manifest, args.out)
        rejected = sum(row['status'] == 'rejected' for row in manifest['records'])
        print(f'Extracted {len(manifest["records"]) - rejected}; rejected {rejected}')
        if rejected:
            raise SystemExit(1)
    elif args.command == 'fit-scaler':
        scaler = fit_manifest_scaler(args.manifest, args.out)
        print(f'Fit train scaler on {len(scaler.training_records)} recordings; counts={scaler.valid_counts}')
    else:
        features = load_note_performance(args.record)
        scaler = load_note_performance_scaler(args.scaler)
        export_scaled_note_performance(features, scaler, args.out)
        print(f'Exported R_scaled[{len(features.row_keys)},11] with masks and beat table')


if __name__ == '__main__':
    main()
